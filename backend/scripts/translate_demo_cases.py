def as_fields(entry: dict) -> dict:
    return {lang: dict(zip(("title", "description", "objective"), vals)) for lang, vals in entry.items()}


def main():
    from sqlalchemy import select
    from app.db import SessionLocal
    from app.models import Case
    db = SessionLocal()
    n = 0
    for c in db.scalars(select(Case).where(Case.is_scenario.is_(False))):
        if c.title in TR:
            c.translations = as_fields(TR[c.title])
            n += 1
    db.commit()
    print(f"translated {n} case(s)")


if __name__ == "__main__":
    main()
